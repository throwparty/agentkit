//! The turn loop: one client prompt → model requests (streamed) →
//! assistant messages persisted, until the model finishes or the
//! request cap trips.
//!
//! v1 runs a single request per turn — the loop shape exists so
//! tool-call iterations (execute via the registry + pipeline,
//! append tool results, request again) slot in without reshaping.

use super::{TurnOutcome, TurnStop};
use crate::providers::{
    ChatContent, ChatMessage, ChatRole, ModelError, ModelProvider, ModelRequest,
};
use crate::store::{Role, SessionStore, StoreError, TurnId};

#[derive(Debug, thiserror::Error)]
pub enum TurnError {
    #[error(transparent)]
    Model(#[from] crate::providers::ModelError),
    #[error(transparent)]
    Store(#[from] StoreError),
}

/// Runs one turn: persists the prompt turn (the user message) is the
/// CALLER's job — this loop persists the assistant response(s).
///
/// `assistant_message_id` is pre-generated by the caller so the streamed
/// chunks and the stored message share one stable identity (one
/// messageId per logical message).
/// `context_length_note` is the actionable message the context-length
/// failure surfaces in-band — the caller builds it naming the
/// configured compaction script (or its absence).
/// Arguments stay explicit (provider, store, ids, prompts, cap, callback):
/// the tool-call loop extends the body, not the signature.
#[allow(clippy::too_many_arguments)]
pub async fn run_turn<P: ModelProvider>(
    provider: &P,
    db: &SessionStore,
    session_id: &crate::store::SessionId,
    turn_id: &TurnId,
    assistant_message_id: &str,
    model: &str,
    system: &str,
    prompt: Vec<ChatContent>,
    prior: Vec<ChatMessage>,
    tools: Vec<crate::providers::ToolDefinition>,
    max_requests: u32,
    context_length_note: &str,
    mut on_usage: impl FnMut(u64, u64, Option<f64>) + Send,
    mut on_delta: impl FnMut(&str) + Send,
    mut on_thought: impl FnMut(&str) + Send,
    mut on_retry: impl FnMut(u32, &str) + Send,
    mut on_tool_call: impl FnMut(
        crate::providers::ModelToolCall,
    ) -> std::pin::Pin<
        Box<dyn std::future::Future<Output = crate::providers::ToolCallOutcome> + Send>,
    >,
) -> Result<TurnOutcome, TurnError> {
    let mut request_count = 0u32;
    let mut history = prior;
    history.push(ChatMessage::with_content(ChatRole::User, prompt));
    // The running usage delta across the turn's requests. A turn issues one
    // request per tool-call round, and each is billed, so the stored delta
    // is their sum — not the last request's alone.
    let mut turn_usage = crate::store::TurnUsage::default();
    // A prior turn may already have made the session's cost known: later
    // updates keep reporting the cumulative total even when this request
    // cannot be priced.
    let mut cost_known = db.session_usage(session_id).await?.cost_usd > 0.0;

    loop {
        request_count += 1;
        if request_count > max_requests {
            // The caller announces in the client before mapping this onto
            // ACP's max_turn_requests stop reason (Quest F9).
            return Ok(TurnOutcome {
                stop: TurnStop::MaxTurnRequests,
                usage: db.session_usage(session_id).await?,
            });
        }

        let request = ModelRequest {
            model: model.to_owned(),
            system: system.to_owned(),
            messages: history.clone(),
            tools: tools.clone(),
        };

        // The messageId: every streamed chunk carries the same identity —
        // chunks are fragments of ONE logical message (the stored assistant
        // message is appended below with exactly this id).
        let message_id = if request_count == 1 {
            assistant_message_id.to_owned()
        } else {
            format!("{assistant_message_id}-r{request_count}")
        };
        let mut text = String::new();
        let mut deltas_flowed = false;
        let mut on_delta = |delta: &str| {
            deltas_flowed = true;
            text.push_str(delta);
            on_delta(delta);
        };
        let response = provider
            .stream_completion(request, &mut on_delta, &mut on_thought)
            .await;
        let response = match response {
            Ok(response) => response,
            // Context-length overflow: actionable, never retried, and
            // streamed in-band so the client is never left guessing. This
            // covers a plain completion error and a stream that failed
            // before any delta — an HTTP 413 "payload too large" arrives
            // the latter way.
            Err(err) if is_context_overflow(&err) => {
                on_delta(context_length_note);
                db.append_message(
                    turn_id,
                    Role::Assistant,
                    &serde_json::json!([{ "type": "text", "text": context_length_note }])
                        .to_string(),
                    None,
                    None,
                    None,
                    Some(&message_id),
                )
                .await?;
                return Ok(TurnOutcome {
                    stop: TurnStop::ContextLength,
                    usage: db.session_usage(session_id).await?,
                });
            }
            // A stream error with NO text: the failure happened before any
            // delta reached the client — retry like a plain transient.
            Err(ModelError::StreamFailed {
                error,
                text: partial,
                ..
            }) if partial.is_empty()
                && super::retry::classify(&error) == super::retry::FailureClass::Retryable
                && request_count < max_requests.min(super::retry::MAX_ATTEMPTS) =>
            {
                on_retry(request_count, &error);
                let delay = super::retry::retry_after_secs(&error)
                    .unwrap_or_else(|| super::retry::backoff(request_count));
                tokio::time::sleep(delay).await;
                continue;
            }
            // Mid-stream failure: the client already saw the deltas —
            // persist the partial text and stream the failure notice so the
            // turn never ends silently (retrying would duplicate the
            // streamed prefix).
            Err(ModelError::StreamFailed {
                text: partial,
                error,
                ..
            }) => {
                let note = format!(
                    "The model connection failed mid-response; the text above is partial. ({error})"
                );
                on_delta(&note);
                db.append_message(
                    turn_id,
                    Role::Assistant,
                    &serde_json::json!([
                        { "type": "text", "text": partial },
                        { "type": "text", "text": note }
                    ])
                    .to_string(),
                    None,
                    None,
                    None,
                    Some(&message_id),
                )
                .await?;
                return Ok(TurnOutcome {
                    stop: TurnStop::EndTurn,
                    usage: db.session_usage(session_id).await?,
                });
            }
            // Retryable without streamed deltas: back off and retry,
            // reporting the attempt as a status card. A retryable failure
            // WITH deltas is impossible (those arrive as StreamFailed).
            Err(ModelError::Completion(text))
                if super::retry::classify(&text) == super::retry::FailureClass::Retryable
                    && !deltas_flowed
                    && request_count < max_requests.min(super::retry::MAX_ATTEMPTS) =>
            {
                on_retry(request_count, &text);
                let delay = super::retry::retry_after_secs(&text)
                    .unwrap_or_else(|| super::retry::backoff(request_count));
                tokio::time::sleep(delay).await;
                continue;
            }
            Err(ModelError::Completion(text)) => {
                // Retries exhausted (or fatal): hard failure — the caller
                // surfaces a JSON-RPC error.
                return Err(TurnError::Model(ModelError::Completion(text)));
            }
            Err(err) => return Err(TurnError::Model(err)),
        };

        // Persist the assistant text when present (tool-call rounds carry
        // no text), and the running usage delta the turn has incurred.
        if !response.text.is_empty() {
            db.append_message(
                turn_id,
                Role::Assistant,
                &serde_json::json!([{ "type": "text", "text": response.text }]).to_string(),
                None,
                None,
                None,
                Some(&message_id),
            )
            .await?;
        }
        // Accumulate: the stored delta is the whole turn's cost, not just
        // the last request's (a multi-request turn otherwise undercounts by
        // every request but the last).
        turn_usage.input_tokens += response.usage.input_tokens;
        turn_usage.output_tokens += response.usage.output_tokens;
        if let Some(cost) = crate::agent::config_options::request_cost(
            model,
            response.usage.input_tokens,
            response.usage.output_tokens,
        ) {
            turn_usage.cost_usd += cost;
            cost_known = true;
        }
        db.set_turn_usage(turn_id, turn_usage).await?;
        // The live usage indicator tracks the latest request's prompt size
        // (the current context), not the running total. Cost is the
        // cumulative session total, omitted until some request is priced.
        let session_usage = db.session_usage(session_id).await?;
        on_usage(
            response.usage.input_tokens,
            response.usage.output_tokens,
            cost_known.then_some(session_usage.cost_usd),
        );

        // A final answer (no tool calls) ends the turn.
        if response.tool_calls.is_empty() {
            return Ok(TurnOutcome {
                stop: TurnStop::EndTurn,
                usage: db.session_usage(session_id).await?,
            });
        }

        // Record the assistant's tool calls, execute each, record its
        // result, and request the model again.
        let content = if response.text.is_empty() {
            Vec::new()
        } else {
            vec![ChatContent::text(response.text.clone())]
        };
        history.push(ChatMessage {
            role: ChatRole::Assistant,
            content,
            tool_calls: response.tool_calls.clone(),
            ..Default::default()
        });
        for call in response.tool_calls {
            let stored_call = db
                .append_message(
                    turn_id,
                    Role::ToolCall,
                    &call.arguments,
                    Some(&call.name),
                    None,
                    None,
                    None,
                )
                .await?;
            let outcome = on_tool_call(call.clone()).await;
            db.append_message(
                turn_id,
                Role::ToolResult,
                &serde_json::json!([{ "type": "text", "text": outcome.content }]).to_string(),
                Some(&call.name),
                Some(&stored_call.id),
                Some(outcome.is_error),
                None,
            )
            .await?;
            history.push(ChatMessage::tool_result(
                call.id.clone(),
                call.name.clone(),
                outcome.content,
            ));
        }
    }
}

/// Whether an error is a context-window overflow: a plain completion
/// error classified as context-length, or a stream that failed before any
/// delta with such an error (an HTTP 413 "payload too large" surfaces this
/// way). A mid-stream failure that already delivered text is not — the
/// partial output stands and the caller reports it separately.
fn is_context_overflow(err: &ModelError) -> bool {
    match err {
        ModelError::Completion(text) => {
            super::retry::classify(text) == super::retry::FailureClass::ContextLength
        }
        ModelError::StreamFailed { error, text, .. } => {
            text.is_empty()
                && super::retry::classify(error) == super::retry::FailureClass::ContextLength
        }
        _ => false,
    }
}

/// The prompt text for the model: text blocks joined, with embedded
/// resource contents inlined. A resource link — a reference the client
/// sent without content, e.g. an oversized file or a client that did not
/// negotiate `embeddedContext` — degrades to its name and URI so the
/// reference is never silently dropped. Used where only text can be sent
/// (compaction and titling); the model prompt uses [`prompt_parts`].
pub fn prompt_text(blocks: &[serde_json::Value]) -> String {
    blocks
        .iter()
        .filter_map(prompt_block_text)
        .collect::<Vec<_>>()
        .join(" ")
}

/// The model prompt in block order: text, embedded resources, resource
/// links, and images. Image data becomes a `data:` URL carrying the MIME
/// type exactly as the client declared it; an image with no data may
/// reference an HTTP(S) or `data:` URI. Any other image is rejected rather
/// than silently dropped.
pub fn prompt_parts(blocks: &[serde_json::Value]) -> Result<Vec<ChatContent>, String> {
    let mut parts = Vec::new();
    for block in blocks {
        if block.get("type").and_then(serde_json::Value::as_str) == Some("image") {
            parts.push(ChatContent::Image {
                url: image_url(block)?,
            });
        } else if let Some(text) = prompt_block_text(block) {
            parts.push(ChatContent::text(text));
        }
    }
    Ok(parts)
}

/// Resolves an ACP image block to a URL the provider can fetch: its base64
/// data with the declared MIME type, or its own URI when no data is set.
fn image_url(block: &serde_json::Value) -> Result<String, String> {
    if let Some(data) = block
        .get("data")
        .and_then(serde_json::Value::as_str)
        .filter(|data| !data.is_empty())
    {
        let mime = block
            .get("mimeType")
            .and_then(serde_json::Value::as_str)
            .filter(|mime| !mime.is_empty())
            .ok_or_else(|| "image content has no media type".to_owned())?;
        return Ok(format!("data:{mime};base64,{data}"));
    }

    let uri = block
        .get("uri")
        .and_then(serde_json::Value::as_str)
        .filter(|uri| !uri.is_empty());
    match uri {
        Some(uri) if uri.starts_with("http://") => Ok(uri.to_owned()),
        Some(uri) if uri.starts_with("https://") => Ok(uri.to_owned()),
        Some(uri) if uri.starts_with("data:") => Ok(uri.to_owned()),
        Some(_) => Err("image content has an unsupported URI scheme".to_owned()),
        None => Err("image content has no data or URI".to_owned()),
    }
}

/// One content block's contribution to the model prompt text.
fn prompt_block_text(block: &serde_json::Value) -> Option<String> {
    // Text block: its own payload. Also covers tool-result and seed
    // messages stored as `{ "type": "text", ... }`.
    if let Some(text) = block.get("text").and_then(serde_json::Value::as_str) {
        return Some(text.to_owned());
    }
    // Embedded resource: the client inlined the referenced file's text.
    if let Some(text) = block
        .get("resource")
        .and_then(|resource| resource.get("text"))
        .and_then(serde_json::Value::as_str)
    {
        return Some(text.to_owned());
    }
    // Resource link: no content, so keep the reference itself.
    if block.get("type").and_then(serde_json::Value::as_str) == Some("resource_link") {
        let name = block
            .get("name")
            .and_then(serde_json::Value::as_str)
            .filter(|name| !name.is_empty());
        let uri = block
            .get("uri")
            .and_then(serde_json::Value::as_str)
            .filter(|uri| !uri.is_empty());
        return match (name, uri) {
            (Some(name), Some(uri)) => Some(format!("[@{name}]({uri})")),
            (Some(name), None) => Some(name.to_owned()),
            (None, Some(uri)) => Some(uri.to_owned()),
            (None, None) => None,
        };
    }
    None
}

#[cfg(test)]
mod tests {
    use super::{prompt_parts, prompt_text, run_turn};
    use crate::providers::{
        ChatContent, ModelProvider, ModelRequest, ModelResponse, ModelToolCall, ModelUsage,
        ToolCallOutcome,
    };
    use crate::store::{SessionKind, SessionStore, TurnKind};
    use std::sync::atomic::{AtomicUsize, Ordering};

    struct TwoRounds(AtomicUsize);

    impl ModelProvider for TwoRounds {
        fn stream_completion(
            &self,
            _request: ModelRequest,
            _on_text_delta: &mut (dyn FnMut(&str) + Send),
            _on_thought_delta: &mut (dyn FnMut(&str) + Send),
        ) -> impl std::future::Future<Output = Result<ModelResponse, crate::providers::ModelError>> + Send
        {
            let round = self.0.fetch_add(1, Ordering::SeqCst);
            async move {
                Ok(if round == 0 {
                    ModelResponse {
                        text: String::new(),
                        tool_calls: vec![ModelToolCall {
                            id: "call-1".to_owned(),
                            name: "test.tool".to_owned(),
                            arguments: "{}".to_owned(),
                        }],
                        usage: ModelUsage {
                            input_tokens: 1_000_000,
                            output_tokens: 0,
                        },
                    }
                } else {
                    ModelResponse {
                        text: "done".to_owned(),
                        tool_calls: Vec::new(),
                        usage: ModelUsage {
                            input_tokens: 0,
                            output_tokens: 500_000,
                        },
                    }
                })
            }
        }
    }

    async fn turn_fixture() -> (SessionStore, crate::store::SessionId, crate::store::TurnId) {
        let store = SessionStore::in_memory();
        let session = store
            .create_session(SessionKind::Interactive, "/tmp", None, None, "{}")
            .await
            .unwrap();
        let turn = store
            .append_turn(
                &session.id,
                None,
                TurnKind::Interaction,
                None,
                Default::default(),
            )
            .await
            .unwrap();
        (store, session.id, turn.id)
    }

    #[tokio::test]
    async fn multi_request_turn_sums_cost_and_reports_the_cumulative_total() {
        let (store, session, turn) = turn_fixture().await;
        let mut usage = Vec::new();
        let outcome = run_turn(
            &TwoRounds(AtomicUsize::new(0)),
            &store,
            &session,
            &turn,
            "assistant-1",
            "openai/gpt-4o",
            "system",
            vec![ChatContent::text("hi")],
            Vec::new(),
            Vec::new(),
            8,
            "note",
            |input, output, cost| usage.push((input, output, cost)),
            |_: &str| {},
            |_: &str| {},
            |_, _| {},
            |_call| {
                Box::pin(async {
                    ToolCallOutcome {
                        content: "ok".to_owned(),
                        is_error: false,
                    }
                })
            },
        )
        .await
        .unwrap();

        assert_eq!(usage.len(), 2);
        assert_eq!(usage[0].2, Some(2.5), "input-only request");
        assert_eq!(usage[1].2, Some(7.5), "cumulative after both requests");
        assert_eq!(outcome.usage.input_tokens, 1_000_000);
        assert_eq!(outcome.usage.output_tokens, 500_000);
        assert!((outcome.usage.cost_usd - 7.5).abs() < 1e-12);
    }

    #[tokio::test]
    async fn unpriced_turn_omits_cost() {
        let (store, session, turn) = turn_fixture().await;
        let mut usage = Vec::new();
        let outcome = run_turn(
            &TwoRounds(AtomicUsize::new(1)),
            &store,
            &session,
            &turn,
            "assistant-1",
            "switchboard/gpt-4o",
            "system",
            vec![ChatContent::text("hi")],
            Vec::new(),
            Vec::new(),
            8,
            "note",
            |input, output, cost| usage.push((input, output, cost)),
            |_: &str| {},
            |_: &str| {},
            |_, _| {},
            crate::providers::ignore_tool_call,
        )
        .await
        .unwrap();

        assert_eq!(usage[0].2, None);
        assert_eq!(outcome.usage.cost_usd, 0.0);
    }

    #[test]
    fn text_blocks_join() {
        let blocks = vec![
            serde_json::json!({ "type": "text", "text": "hello" }),
            serde_json::json!({ "type": "text", "text": "world" }),
        ];
        assert_eq!(prompt_text(&blocks), "hello world");
    }

    #[test]
    fn embedded_resource_contents_inline() {
        let blocks = vec![serde_json::json!({
            "type": "resource",
            "resource": { "uri": "file:///a.md", "text": "# Title" }
        })];
        assert_eq!(prompt_text(&blocks), "# Title");
    }

    #[test]
    fn resource_link_keeps_the_reference() {
        let blocks = vec![serde_json::json!({
            "type": "resource_link",
            "name": "a.md",
            "uri": "file:///a.md"
        })];
        assert_eq!(prompt_text(&blocks), "[@a.md](file:///a.md)");
    }

    #[test]
    fn mixed_blocks_keep_order() {
        let blocks = vec![
            serde_json::json!({ "type": "text", "text": "see" }),
            serde_json::json!({ "type": "resource_link", "name": "a.md", "uri": "file:///a.md" }),
            serde_json::json!({ "type": "text", "text": "and" }),
        ];
        assert_eq!(prompt_text(&blocks), "see [@a.md](file:///a.md) and");
    }

    #[test]
    fn prompt_text_omits_images() {
        let blocks = vec![
            serde_json::json!({ "type": "text", "text": "look" }),
            serde_json::json!({ "type": "image", "data": "AAAA", "mimeType": "image/png" }),
        ];
        assert_eq!(prompt_text(&blocks), "look");
    }

    #[test]
    fn prompt_parts_preserve_image_order_and_declared_mime() {
        let blocks = vec![
            serde_json::json!({ "type": "text", "text": "before" }),
            serde_json::json!({
                "type": "image",
                "data": "AAAA",
                "mimeType": "image/x-unknown"
            }),
            serde_json::json!({ "type": "text", "text": "after" }),
        ];
        assert_eq!(
            prompt_parts(&blocks).unwrap(),
            vec![
                ChatContent::text("before"),
                ChatContent::Image {
                    url: "data:image/x-unknown;base64,AAAA".to_owned()
                },
                ChatContent::text("after"),
            ]
        );
    }

    #[test]
    fn prompt_parts_accept_a_remote_image_uri() {
        let blocks = vec![serde_json::json!({
            "type": "image",
            "data": "",
            "mimeType": "image/png",
            "uri": "https://example.test/a.png"
        })];
        assert_eq!(
            prompt_parts(&blocks).unwrap(),
            vec![ChatContent::Image {
                url: "https://example.test/a.png".to_owned()
            }]
        );
    }

    #[test]
    fn prompt_parts_reject_an_image_with_no_data_or_uri() {
        let blocks = vec![serde_json::json!({
            "type": "image",
            "data": "",
            "mimeType": "image/png"
        })];
        assert_eq!(
            prompt_parts(&blocks).unwrap_err(),
            "image content has no data or URI"
        );
    }
}
